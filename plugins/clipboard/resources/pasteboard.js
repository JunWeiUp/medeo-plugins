// The plugin's only window onto the macOS pasteboard, run with `osascript -l JavaScript`
// (always present, no Xcode). AppKit posts no change notification, so `watch` checks
// changeCount twice a second, as every clipboard manager does, and prints one JSON line
// per copy; `write <request.json>` puts a stored entry back; `paste` presses ⌘V in the
// frontmost app; `trusted [prompt]` reports (or asks for) the Accessibility grant ⌘V needs.
ObjC.import('AppKit');
ObjC.import('Foundation');

const MAX_TEXT = 1024 * 1024;
const pb = $.NSPasteboard.generalPasteboard;
const out = $.NSFileHandle.fileHandleWithStandardOutput;
const emit = value => out.writeData($(JSON.stringify(value) + '\n').dataUsingEncoding($.NSUTF8StringEncoding));
const str = type => { const s = pb.stringForType(type); return s.isNil() ? null : s.js; };
// Password managers mark secrets; they never enter the history.
const SKIP = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType', 'com.agilebits.onepassword'];

function files() {
  const items = ObjC.unwrap(pb.pasteboardItems) || [];
  const paths = [];
  for (const item of items) {
    const url = item.stringForType('public.file-url');
    if (!url.isNil()) { const p = $.NSURL.URLWithString(url).path; if (!p.isNil()) paths.push(p.js); }
  }
  return paths;
}
function image(dir, count) {
  let data = pb.dataForType('public.png');
  if (data.isNil()) {
    const tiff = pb.dataForType('public.tiff');
    if (tiff.isNil()) return null;
    data = $.NSBitmapImageRep.imageRepWithData(tiff).representationUsingTypeProperties($.NSBitmapImageFileTypePNG, $());
  }
  const path = `${dir}/incoming-${count}.png`;
  return data.writeToFileAtomically(path, true) ? path : null;
}
function read(dir, count) {
  const types = ObjC.deepUnwrap(pb.types) || [];
  const app = $.NSWorkspace.sharedWorkspace.frontmostApplication;
  const entry = { count, types, app: app.isNil() ? null : app.localizedName.js, bundle: app.isNil() ? null : app.bundleIdentifier.js };
  if (types.some(t => SKIP.includes(t))) return { ...entry, skipped: 'concealed' };
  const clip = s => s !== null && s.length > MAX_TEXT ? null : s;
  if (types.includes('public.file-url')) return { ...entry, files: files(), text: clip(str('public.utf8-plain-text')) };
  if (types.includes('public.png') || types.includes('public.tiff')) {
    const path = image(dir, count);
    if (path) return { ...entry, image: path };
  }
  const text = clip(str('public.utf8-plain-text'));
  const html = types.includes('public.html') ? clip(str('public.html')) : null;
  const rtf = !html && types.includes('public.rtf') ? clip(str('public.rtf')) : null;
  if (text === null && html === null && rtf === null) return { ...entry, skipped: 'empty' };
  return { ...entry, text, html, rtf };
}
function watch(dir) {
  let last = pb.changeCount;
  emit({ ready: last });
  for (;;) {
    delay(0.5);
    const count = pb.changeCount;
    if (count === last) continue;
    last = count;
    try { emit(read(dir, count)); } catch (error) { emit({ count, error: String(error) }); }
  }
}
function write(file) {
  const request = JSON.parse($.NSString.stringWithContentsOfFileEncodingError(file, $.NSUTF8StringEncoding, $()).js);
  pb.clearContents;
  let ok;
  if (request.files) ok = pb.writeObjects($(request.files.map(p => $.NSURL.fileURLWithPath(p))));
  else if (request.image) {
    const data = $.NSData.dataWithContentsOfFile(request.image);
    const item = $.NSPasteboardItem.alloc.init;
    item.setDataForType(data, 'public.png');
    const tiff = $.NSImage.alloc.initWithData(data).TIFFRepresentation;
    if (!tiff.isNil()) item.setDataForType(tiff, 'public.tiff');
    ok = pb.writeObjects($([item]));
  } else {
    const item = $.NSPasteboardItem.alloc.init;
    if (request.html) item.setStringForType(request.html, 'public.html');
    if (request.rtf) item.setStringForType(request.rtf, 'public.rtf');
    if (request.text !== undefined && request.text !== null) item.setStringForType(request.text, 'public.utf8-plain-text');
    ok = pb.writeObjects($([item]));
  }
  emit({ ok: !!ok, count: pb.changeCount });
}
// macOS drops synthetic key events from apps without the Accessibility grant (the grant
// belongs to Medeo, the app that started this helper). A HID-state source posted to the
// session tap is what reaches the frontmost app.
function paste() {
  ObjC.import('CoreGraphics');
  ObjC.bindFunction('CGEventSourceCreate', ['void*', ['int']]);
  ObjC.bindFunction('CGEventCreateKeyboardEvent', ['void*', ['void*', 'unsigned short', 'bool']]);
  ObjC.bindFunction('CGEventSetFlags', ['void', ['void*', 'unsigned long long']]);
  ObjC.bindFunction('CGEventPost', ['void', ['unsigned int', 'void*']]);
  const KEY_V = 9, COMMAND = 0x100000, HID_STATE = 1, SESSION_TAP = 1;
  const source = $.CGEventSourceCreate(HID_STATE);
  for (const down of [true, false]) {
    const event = $.CGEventCreateKeyboardEvent(source, KEY_V, down);
    $.CGEventSetFlags(event, COMMAND);
    $.CGEventPost(SESSION_TAP, event);
    delay(0.02);
  }
  emit({ ok: true });
}
function trusted(prompt) {
  ObjC.import('ApplicationServices');
  const ok = prompt ? $.AXIsProcessTrustedWithOptions($({ AXTrustedCheckOptionPrompt: true })) : $.AXIsProcessTrusted();
  emit({ trusted: !!ok });
}
function run(argv) {
  if (argv[0] === 'watch') return watch(argv[1]);
  if (argv[0] === 'write') return write(argv[1]);
  if (argv[0] === 'paste') return paste();
  if (argv[0] === 'trusted') return trusted(argv[1] === 'prompt');
  throw new Error('usage: watch <dir> | write <request.json> | paste | trusted [prompt]');
}
